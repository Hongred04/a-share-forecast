"""交易日历测试。

为什么单独一个文件
    `HOLIDAYS` 是一张会过期的表。过期不会报错，只会让 target 悄悄算错一天，
    而这种错误要等到第二天对不上成绩才会被发现——代价太大。
    这个测试把"日历是否还够用"变成每次 `run.py test` 都会喊出来的事。

覆盖
    1. 已公布的 2026/2027 休市日必须判成非交易日（含春节、国庆这种连休）
    2. 调休上班日（周末但上班）A 股仍然不开市，不能被判成交易日
    3. 普通工作日必须是交易日（防止过度排除）
    4. 覆盖范围到期时必须报警（stale=True），且提前 90 天就开始报
    5. 从日线反推休市日：只补区间内部缺口，尾部截断不能误判

用法
    python tests/trading_calendar.py
"""
from __future__ import annotations

import datetime as dt
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from core import datahub as D  # noqa: E402

fails: list[str] = []


def ok(cond: bool, msg: str) -> None:
    if cond:
        print(f"  ✓ {msg}")
    else:
        fails.append(msg)
        print(f"  ✗ {msg}")


def day(s: str) -> dt.date:
    return dt.date.fromisoformat(s)


# ---------------------------------------------------------------------------
print("已公布的休市日")
# ---------------------------------------------------------------------------
OFF = [
    # 2026
    "2026-01-01", "2026-02-16", "2026-02-17", "2026-02-18", "2026-02-19",
    "2026-02-20", "2026-02-23", "2026-04-06", "2026-05-01", "2026-05-04",
    "2026-05-05", "2026-06-19", "2026-09-25", "2026-10-01", "2026-10-07",
    # 2027（国办 2026-11-05 通知）
    "2027-01-01",                                    # 元旦
    "2027-02-05", "2027-02-08", "2027-02-09",        # 春节
    "2027-02-10", "2027-02-11", "2027-02-12",
    "2027-04-05",                                    # 清明
    "2027-05-03", "2027-05-04", "2027-05-05",        # 劳动节
    "2027-06-09",                                    # 端午
    "2027-09-15",                                    # 中秋
    "2027-10-01", "2027-10-04", "2027-10-05",        # 国庆
    "2027-10-06", "2027-10-07",
]
for s in OFF:
    ok(not D.is_trading_day(day(s)), f"{s} 应休市")

# ---------------------------------------------------------------------------
print("\n调休上班日：A 股仍不开市")
# ---------------------------------------------------------------------------
# 这五个日子国务院规定要上班，但交易所不交易。写程序时最容易在这里想当然。
for s in ["2027-01-31", "2027-02-14", "2027-05-08", "2027-09-26", "2027-10-09"]:
    d = day(s)
    if d.weekday() >= 5:
        ok(not D.is_trading_day(d), f"{s}（周{'一二三四五六日'[d.weekday()]}调休上班）应休市")

# ---------------------------------------------------------------------------
print("\n普通工作日")
# ---------------------------------------------------------------------------
for s in ["2026-11-09", "2026-11-10", "2027-03-01", "2027-07-15", "2027-11-08"]:
    ok(D.is_trading_day(day(s)), f"{s} 应是交易日")

# ---------------------------------------------------------------------------
print("\n连休后的首个交易日")
# ---------------------------------------------------------------------------
CASES = [
    ("2026-10-08", "2026-10-09"),   # 国庆后
    ("2027-02-12", "2027-02-15"),   # 春节最后一天 → 2/15 周一
    ("2027-10-07", "2027-10-08"),   # 国庆最后一天 → 10/8 周五
    ("2027-01-01", "2027-01-04"),   # 元旦 → 1/4 周一
]
for frm, want in CASES:
    got = D.next_trading_day(day(frm)).isoformat()
    ok(got == want, f"{frm} 的下一交易日应为 {want}，实际 {got}")

# ---------------------------------------------------------------------------
print("\n覆盖范围到期提醒")
# ---------------------------------------------------------------------------
ok(D.calendar_coverage(day("2026-11-07"))["stale"] is False,
   "2026-11-07 日历应仍有效")
# 覆盖年份的最后 90 天内就要开始提醒，不能等元旦当天
ok(D.calendar_coverage(day("2027-10-15"))["stale"] is True,
   "2027-10-15（距年底 78 天）应提前报警")
ok(D.calendar_coverage(day("2027-06-01"))["stale"] is False,
   "2027-06-01 距离年底还远，不应报警")
c28 = D.calendar_coverage(day("2028-03-01"))
ok(c28["stale"] is True and c28["covered"] is False, "2028 年超出覆盖范围应报警")
ok(bool(c28["msg"]), "报警时必须带一句人能看懂的话")

# ---------------------------------------------------------------------------
print("\n从日线反推（尾部截断 vs 内部缺口）")
# ---------------------------------------------------------------------------
D._derived.clear()
seq = [f"2026-10-{i:02d}" for i in range(1, 32)] + \
      ["2026-11-02", "2026-11-03", "2026-11-04", "2026-11-05"]
seq = [s for s in seq if day(s).weekday() < 5]
D.sync_from_kline(seq)
ok(D.is_trading_day(day("2026-11-06")),
   "数据尾部截断时，11-06 不能被误判成休市")

D._derived.clear()
seq2 = [s for s in seq if s != "2026-10-15"]
n = D.sync_from_kline(seq2)
ok(not D.is_trading_day(day("2026-10-15")),
   "区间内部缺失的工作日应被判为休市")
ok(n >= 1, "内部缺口应被补进日历")

D._derived.clear()
ok(D.sync_from_kline(["2026-11-05"]) == 0, "样本太少时不应改日历")
ok(D.sync_from_kline(None) == 0, "传 None 应安全返回")
D._derived.clear()

# ---------------------------------------------------------------------------
print()
if fails:
    print(f"{len(fails)} 项未通过：")
    for f in fails:
        print(f"  - {f}")
    sys.exit(1)
print("全部通过")
